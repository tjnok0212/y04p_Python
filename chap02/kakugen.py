class Main():
    def __init__(self):
        self.kakugen1()
        self.kakugen2()
        return

    def kakugen1(self):
        # 格言を表示する
        print("たたきつづけなさい")
        print("そうすれば開かれます")
        return

    def kakugen2(self):
        print("剣で突き刺すかのように", end="")
        print("話す者がいる。", end="")
        print("しかし賢い者たちの舌は", end="")
        print("人をいやす。")
        return


if __name__ == "__main__":
    Main()